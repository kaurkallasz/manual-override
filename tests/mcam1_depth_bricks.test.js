const assert=require('node:assert/strict');
const {grid,color,relativePoints,motionScale}=require('../sandboxes/gamemaster/prototypes/mcam1-depth/web/app.js');
const points=[{x:.1,y:.1,distance_mm:80,depth_mm:70},{x:.11,y:.11,distance_mm:82},{x:.7,y:.7,distance_mm:240}];
const map=grid(points,480,320,20);
assert.equal(map.cells.length,2);assert.equal(map.cells[0].distance,81);
assert.equal(map.coverage,2/(24*16));
assert.notEqual(color(81,30,300),color(240,30,300));
assert.equal(grid([...points,{x:.1,y:.1,distance_mm:300}],480,320,20).cells.length,1,'Mixed foreground/background cells must stay unknown');
assert.equal(grid([{x:.2,y:.2,depth_mm:100}],480,320,12).cells[0].distance,100,'Existing forward-depth samples remain supported');
assert.equal(grid([{x:1,y:.2,distance_mm:90},{x:.2,y:.2,distance_mm:NaN},{x:.2,y:.2,distance_mm:0}],480,320,12).cells.length,0);
assert.equal(grid([],480,320,12).cells.length,0,'Unknown cells are never filled from adjacent measurements');
assert.equal(grid([{x:.1,y:.1,distance_mm:80,views:5},{x:.11,y:.11,distance_mm:81,views:3}],480,320,20).cells[0].views,3,'A brick reports the weakest feature support within its cell');
console.log('PASS: measured cells only, distance colors, legacy depth, mixed-boundary rejection, empty and invalid samples');
const data=Float32Array.from({length:48*32},(_,i)=>1+(i%48)/48+Math.floor(i/48)/64);
const relative=relativePoints(data,48,32,480,320);
assert(relative.length>2000);assert.equal(Math.min(...relative.map(p=>p.relative_depth)),0);assert.equal(Math.max(...relative.map(p=>p.relative_depth)),1);
assert(relative[0].relative_depth>relative.at(-1).relative_depth,'Higher predicted inverse depth is nearer');
assert(grid(relative,480,320,12,true).cells.length>900,'Relative colors do not require millimetres');
assert.equal(relativePoints(new Float32Array(100).fill(3),10,10,480,320).length,0,'Flat predictions do not invent a depth range');
const anchors=[];
for(let y=2;y<32;y+=4)for(let x=2;x<48;x+=4)anchors.push({x:x/48,y:y/32,depth_mm:1/(.01*data[y*48+x]+.002)});
const scale=motionScale(data,48,32,anchors);
assert(scale);assert(Math.abs(scale.slope-.01)<1e-8);assert(Math.abs(scale.offset-.002)<1e-8);
assert.equal(motionScale(data,48,32,anchors.slice(0,8)),null,'Too few motion anchors cannot establish scale');
assert.equal(motionScale(data,48,32,anchors.map(p=>({...p,depth_mm:100}))),null,'One plane cannot resolve AI scale and offset');
assert.equal(motionScale(data,48,32,anchors.map((p,i)=>({...p,depth_mm:anchors.at(-1-i).depth_mm}))),null,'Reversed depth ordering cannot refine the model');
console.log('PASS: relative near/far predictions, no fake millimetres, robust same-frame motion scale and rejection of insufficient or inconsistent anchors');
